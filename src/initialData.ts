export function getRealEquipmentImage(category?: string, name?: string): string {
  const n = (name || '').toLowerCase();
  const c = (category || '').toLowerCase();
  if (n.includes('oxygen') || n.includes('resp') || c === 'respiratory') return OXYGEN_IMAGE;
  if (n.includes('monitor') || n.includes('telemetry') || c === 'monitoring') return MONITOR_IMAGE;
  if (n.includes('bed') || n.includes('icu')) return ICU_BED_IMAGE;
  if (n.includes('ecg') || n.includes('ekg') || n.includes('electrocard')) return ECG_IMAGE;
  if (n.includes('wheelchair') || c === 'mobility') return WHEELCHAIR_IMAGE;
  if (n.includes('autoclave') || n.includes('steril') || c === 'surgical') return AUTOCLAVE_IMAGE;
  if (n.includes('ultrasound') || n.includes('sonograph') || n.includes('doppler')) return ULTRASOUND_IMAGE;
  if (c === 'diagnostic') return ECG_IMAGE;
  return MONITOR_IMAGE;
}

